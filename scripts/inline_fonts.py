#!/usr/bin/env python3
"""Inline the theme's fonts into the stylesheet as data: URIs.

Why this exists: NetNewsWire gives an article theme no way to reference a file
inside its own bundle. `ArticleTheme.swift` reads `stylesheet.css` into a
String, `ArticleRenderer` splices that String into the article HTML, and
`DetailWebViewController` loads it with

    webView.loadHTMLString(html, baseURL: URL(string: rendering.baseURL))

where `rendering.baseURL` is the *article's* URL, not the theme folder. A
relative `url(fonts/x.woff2)` therefore resolves against the article site and
404s; a theme's bundled fonts never load. (Verified: a theme with a relative
font URL reports zero loaded FontFaces in a WKWebView loaded the same way,
while the same font as a data: URI loads and renders.)

So the fonts are inlined here. Costs and constraints, for whoever touches this
next:

  - `stylesheet.css` grows by ~4/3 of the font bytes: 0.25 MB, from the two mono
    faces (176 KB). It was 15 MB while three IBM Plex Sans SC statics were
    embedded for Chinese, and 0.43 MB while an embedded Geist covered Latin.
    Both are gone; both scripts are the system's now.
  - The whole thing is one string that the app inlines into every article's
    HTML. Measured in a WKWebView harness, the first render is not measurably
    slower than with external font URLs — the payload is local, not networked.
  - IBM Plex Mono Var is the only embedded face, and it is under the OFL 1.1:
    its bytes are embedded whole and unmodified (base64 of the release files),
    and the licence ships in fonts/. IBM Plex declares the reserved font name
    "Plex", which a subsetted or converted copy could not keep — so do not
    subset, convert or rename these either. Latin and Chinese are both the
    system's now (Avenir Next / Avenir, and PingFang SC): no bytes for either.

    python3 scripts/inline_fonts.py [output.css]

Without an argument it writes dist/stylesheet.css — the stylesheet the bundle
ships, which is the inlined faces followed by the theme's own rules. build.sh
passes the bundle's path directly, so no intermediate file is left behind;
make_catalog.py calls `build()` in-process and appends stylesheet.css itself.
Both go through here, so what you look at is exactly the CSS the bundle carries.
"""

import base64
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "src", "fonts")
SOURCES = ("vendored-fonts.css",)
STYLESHEET = os.path.join(ROOT, "src", "stylesheet.css")
DEFAULT_OUT = os.path.join(ROOT, "dist", "stylesheet.css")

# url(fonts/whatever.woff2) — unquoted in both generated stylesheets.
REF_RE = re.compile(r"url\(\s*['\"]?fonts/(?P<name>[^'\")\s]+)['\"]?\s*\)")

MIME = {".woff2": "font/woff2", ".ttf": "font/ttf", ".otf": "font/otf"}

HEADER = """/* Generated by scripts/inline_fonts.py — do not edit by hand.
   Every font below is embedded as a data: URI, because NetNewsWire loads a
   theme's stylesheet with the article's URL as the base URL: a relative
   url(fonts/..) cannot resolve, so a theme's bundled font files never load.
   Inlining is the only self-contained way to get these faces into the app.
   One licence per face still ships in fonts/. */
"""


def inline(css: str, source: str) -> tuple[str, list[str]]:
    """Replace every url(fonts/<file>) with a data: URI. Returns (css, inlined)."""
    inlined: list[str] = []

    def replace(match: re.Match) -> str:
        name = match.group("name")
        path = os.path.join(FONT_DIR, name)
        if not os.path.isfile(path):
            raise SystemExit(f"{source}: references missing font {path}")
        ext = os.path.splitext(name)[1].lower()
        if ext not in MIME:
            raise SystemExit(f"{source}: don't know the MIME type for {name}")
        with open(path, "rb") as fh:
            data = fh.read()
        inlined.append(f"{name} ({len(data) / 1024:.0f} KB)")
        return f"url(data:{MIME[ext]};base64,{base64.b64encode(data).decode('ascii')})"

    return REF_RE.sub(replace, css), inlined


def build(verbose: bool = True) -> str:
    """The generated @font-face blocks with the fonts inlined."""
    parts = []
    for name in SOURCES:
        path = os.path.join(FONT_DIR, name)
        with open(path) as fh:
            css, inlined = inline(fh.read(), name)
        if verbose:
            for entry in inlined:
                print(f"  inlined {entry}")
        parts.append(css)
    return HEADER + "\n" + "\n".join(parts)


def main() -> int:
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    with open(STYLESHEET) as fh:
        css = build() + "\n" + fh.read()
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as fh:
        fh.write(css)
    print(f"  {os.path.relpath(out, ROOT)}  {len(css.encode()) / 1024 / 1024:.1f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
